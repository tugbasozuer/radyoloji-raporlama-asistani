-- V1: ilk sema. Tablolar, foreign key'lerin gosterdigi tablo once olusacak sekilde siralidir.
-- Enum sutunlari VARCHAR olarak, enum sabitinin adiyla (STRING) saklanir.

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(30)  NOT NULL
);

CREATE TABLE patient (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name           VARCHAR(255) NOT NULL,
    birth_date          DATE         NOT NULL,
    gender              VARCHAR(30)  NOT NULL,
    patient_file_number VARCHAR(255) NOT NULL UNIQUE,
    national_id         VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE exam (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id                 BIGINT       NOT NULL REFERENCES patient(id),
    protocol_number            VARCHAR(255) NOT NULL UNIQUE,
    exam_type                  VARCHAR(30)  NOT NULL,
    anatomical_region          VARCHAR(30)  NOT NULL,
    exam_date_time             TIMESTAMP    NOT NULL,
    requester                  VARCHAR(255) NOT NULL,
    from_emergency_department  BOOLEAN      NOT NULL
);

CREATE TABLE findings_template (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_type         VARCHAR(30) NOT NULL,
    anatomical_region VARCHAR(30) NOT NULL,
    template_text     TEXT        NOT NULL,
    UNIQUE (exam_type, anatomical_region)
);

CREATE TABLE result_category (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name            VARCHAR(255) NOT NULL UNIQUE,
    approved_sentence        TEXT         NOT NULL,
    associated_urgency_level VARCHAR(30)  NOT NULL
);

CREATE TABLE report (
    id                                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id                             BIGINT      NOT NULL REFERENCES exam(id),
    patient_id                          BIGINT      NOT NULL REFERENCES patient(id),
    clinical_findings_and_pre_diagnosis TEXT,
    findings_exception                  TEXT,
    result_plan_statement               TEXT,
    generated_findings                  TEXT,
    generated_result                    TEXT,
    urgency_level                       VARCHAR(30),
    status                              VARCHAR(30) NOT NULL,
    ai_assisted                         BOOLEAN     NOT NULL,
    previous_record_id                  BIGINT      REFERENCES report(id),
    created_by_id                       BIGINT      NOT NULL REFERENCES app_user(id),
    approved_by_id                      BIGINT      REFERENCES app_user(id),
    created_at                          TIMESTAMP   NOT NULL,
    approved_at                         TIMESTAMP
);

CREATE TABLE report_result_category (
    report_id          BIGINT NOT NULL REFERENCES report(id),
    result_category_id BIGINT NOT NULL REFERENCES result_category(id),
    PRIMARY KEY (report_id, result_category_id)
);

-- PostgreSQL foreign key sutunlarina otomatik index koymaz; sik sorgulanan baglar icin ekliyoruz.
CREATE INDEX idx_exam_patient_id        ON exam(patient_id);
CREATE INDEX idx_report_exam_id         ON report(exam_id);
CREATE INDEX idx_report_patient_id      ON report(patient_id);
CREATE INDEX idx_report_created_by_id   ON report(created_by_id);
CREATE INDEX idx_report_previous_record ON report(previous_record_id);
