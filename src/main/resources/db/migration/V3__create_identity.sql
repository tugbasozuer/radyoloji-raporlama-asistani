-- V3: kullanicinin kimlik/profil bilgileri. app_user ile birebir iliskilidir
-- (app_user_id UNIQUE: bir kullanicinin tek kimligi olur).

CREATE TABLE identity (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_user_id         BIGINT       NOT NULL UNIQUE REFERENCES app_user(id),
    full_name           VARCHAR(255) NOT NULL,
    phone_number        VARCHAR(30),
    title               VARCHAR(100),
    registration_number VARCHAR(50),
    department          VARCHAR(100),
    created_at          TIMESTAMP    NOT NULL
);

-- V3 oncesinde olusturulmus kullanicilar varsa kimliksiz kalmasinlar:
-- gecici olarak ad soyad yerine e-posta yazilir.
INSERT INTO identity (app_user_id, full_name, created_at)
SELECT id, email, CURRENT_TIMESTAMP FROM app_user;
